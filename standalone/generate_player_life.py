"""Assemble two event-only life hooks, preserving the original ARM64 machine state."""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent
from keystone import Ks, KS_ARCH_ARM64, KS_MODE_LITTLE_ENDIAN

sites = (("faint", 0x053cf874, 0x07d46d80, 19, 1, "strb w21, [x19, #0x62a]"),
         ("revive", 0x053b6868, 0x07d46ec0, 20, 0, "strb wzr, [x20, #0x62a]"))
k = Ks(KS_ARCH_ARM64, KS_MODE_LITTLE_ENDIAN)
lines = ["// SPDX-License-Identifier: GPL-2.0-or-later", "// Generated by generate_player_life.py"]
for name, hook, cave, player_register, dying, original in sites:
    asm = [original, "sub sp, sp, #0x300"]
    asm += [f"stp x{i}, x{i+1}, [sp, #{i*8}]" for i in range(0,30,2)]
    asm += ["str x30, [sp, #240]", "mrs x9, nzcv", "str x9, [sp, #248]"]
    asm += [f"stp q{i}, q{i+1}, [sp, #{256+i*16}]" for i in range(0,32,2)]
    asm += [f"mov x0, x{player_register}", f"mov w1, #{dying}", "ldr x16, handler", "blr x16"]
    asm += [f"ldp q{i}, q{i+1}, [sp, #{256+i*16}]" for i in range(0,32,2)]
    asm += ["ldr x9, [sp, #248]", "msr nzcv, x9", "ldr x30, [sp, #240]"]
    asm += [f"ldp x{i}, x{i+1}, [sp, #{i*8}]" for i in range(0,30,2)]
    asm += ["add sp, sp, #0x300", f"b {hook+4}", ".balign 8", "handler:", ".quad 0"]
    data = bytes(k.asm("\n".join(asm), addr=cave)[0])
    branch = bytes(k.asm(f"b {cave}", addr=hook)[0])
    assert len(data) <= 0x140 and cave + len(data) <= 0x07d47000
    assert data[-8:] == bytes(8)
    label = name.upper()
    lines += [f"#define MHR_{label}_HOOK 0x{hook:x}UL", f"#define MHR_{label}_CAVE 0x{cave:x}UL",
              f"#define MHR_{label}_BRANCH 0x{int.from_bytes(branch,'little'):08x}U",
              f"#define MHR_{label}_ORIGINAL 0x{int.from_bytes(data[:4],'little'):08x}U",
              f"#define MHR_{label}_HANDLER_OFFSET {len(data)-8}",
              f"static const unsigned char mhr_{name}_code[] = {{"]
    for i in range(0,len(data),12): lines.append("    "+", ".join(f"0x{x:02x}" for x in data[i:i+12])+",")
    lines += ["};"]
    print(name, "hook", hex(hook), "cave", hex(cave), "bytes", len(data))
(ROOT / "src/player_life_code.h").write_text("\n".join(lines)+"\n")
