"""Assemble the independent capture trampoline, with a runtime state pointer."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
from keystone import Ks, KS_ARCH_ARM64, KS_MODE_LITTLE_ENDIAN

CODE = """
    str s0, [x26, #16]
    cbnz w23, done
    cbnz w22, done
    stp x8, x9, [sp, #-32]!
    stp x10, x11, [sp, #16]
    ldr x9, [x21, #80]
    ldr w9, [x9, #720]
    cbz w9, skip
    tbnz w9, #12, skip
    ldr x8, state_pointer
    ldr w10, [x8, #16]
    add w10, w10, #1
    str w10, [x8, #16]
    dmb ish
    str w9, [x8, #20]
    ldr x9, [x26, #16]
    str x9, [x8]
    str x26, [x8, #8]
    str x21, [x8, #24]
    add w10, w10, #1
    add x11, x8, #16
    stlr w10, [x11]
skip:
    ldp x10, x11, [sp, #16]
    ldp x8, x9, [sp], #32
done:
    b 0x0501adb4
    .balign 8
state_pointer:
    .quad 0
"""
payload, _ = Ks(KS_ARCH_ARM64, KS_MODE_LITTLE_ENDIAN).asm(CODE, addr=0x07d46d00)
payload = bytes(payload)
assert payload[-8:] == bytes(8)
lines = ["// SPDX-License-Identifier: GPL-2.0-or-later",
         "// Generated by standalone/generate_capture.py.",
         f"#define MHR_STATE_LITERAL_OFFSET {len(payload) - 8}",
         "static const unsigned char mhr_capture_code[] = {"]
for i in range(0, len(payload), 12):
    lines.append("    " + ", ".join(f"0x{x:02x}" for x in payload[i:i + 12]) + ",")
lines.append("};\n")
(ROOT / "src/capture_code.h").write_text("\n".join(lines))
print("Capture trampoline:", len(payload), "bytes; state pointer at", len(payload) - 8)
